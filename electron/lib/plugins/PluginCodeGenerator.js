  _sanitizeId(id) {
    return (
      String(id || 'unknown')
        .toLowerCase()
        .replace(/[^a-z0-9_-]/g, '')
        .replace(/-+/g, '-')
        .replace(/^-+|-+$/g, '') || 'unknown'
    );
  }

  _escapeString(str) {
    return String(str || '')
      .replace(/\\/g, '\\\\')
      .replace(/'/g, "\\'")
      .replace(/\r/g, '\\r')
      .replace(/\n/g, '\\n')
      .replace(/\t/g, '\\t')
      .replace(/\u2028/g, '\\u2028')
      .replace(/\u2029/g, '\\u2029');
  }

  _escapeSelector(sel) {
    return this._escapeString(sel);
  }

  _escapeComment(str) {
    return String(str || '')
      .replace(/\*\//g, '* /')
      .replace(/[\r\n\u2028\u2029]/g, ' ');
  }
